import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import path from 'node:path';
import {createServer} from 'vite';
import {chromium} from 'playwright';

const out=path.resolve('artifacts/document-ui-compact-review-20261022');
await fs.mkdir(out,{recursive:true});
const checks=[],screens=[],errors=[];
let server,browser;
function pass(note){checks.push(note);console.log('PASS '+note);}
try{
 server=await createServer({server:{host:'127.0.0.1',port:52996,strictPort:true,hmr:false},clearScreen:false,logLevel:'error'});
 await server.listen();
 browser=await chromium.launch({channel:'msedge',headless:true});
 const page=await browser.newPage({viewport:{width:1440,height:960},deviceScaleFactor:1});
 page.on('pageerror',err=>errors.push(err.message));
 page.on('console',message=>{if(message.type()==='error')errors.push(message.text());});
 const url='http://127.0.0.1:52996/tools/ui-review/entries/document-ui-review.html';
 await page.goto(url,{waitUntil:'networkidle'});
 await page.getByRole('button',{name:'选择客户 / 快速建档'}).waitFor();
 const shot=async name=>{await page.screenshot({path:path.join(out,name+'.png'),fullPage:true});screens.push(name+'.png');};
 await shot('01-editor-desktop');
 assert.equal(await page.locator('input[name="customerName"]').count(),0);
 assert.equal(await page.getByText('上一页客户').count(),0);
 pass('新建单据首屏客户仅一个紧凑字段，不重复展示只读输入或长列表');
 const trigger=page.getByRole('button',{name:'选择客户 / 快速建档'});
 await trigger.click();
 const dialog=page.getByRole('dialog',{name:'选择客户/收货单位'});
 await dialog.waitFor();
 await page.getByRole('textbox',{name:'搜索客户名称、联系人或品牌'}).fill('华锦');
 await dialog.getByRole('button',{name:'选择',exact:true}).first().click();
 await shot('02-customer-select-dialog');
 await dialog.getByRole('button',{name:'确认使用'}).click();
 await page.getByRole('button',{name:'华锦纺织贸易'}).waitFor();
 assert.equal(await dialog.count(),0);
 pass('客户名称、品牌、联系人搜索及选择可用，确认后页面只显示客户名称');
 await page.getByRole('button',{name:'华锦纺织贸易'}).click();
 await dialog.getByRole('button',{name:'快速建档'}).click();
 await dialog.getByRole('textbox',{name:'客户名称'}).fill('暂存客户');
 await shot('03-customer-quick-profile-dialog');
 await dialog.getByRole('button',{name:'取消',exact:true}).click();
 assert.equal(await page.getByRole('button',{name:'华锦纺织贸易'}).count(),1);
 pass('快速建档取消不会改变已选客户或额外提交客户');
 await page.getByRole('button',{name:'华锦纺织贸易'}).click();
 await dialog.getByRole('button',{name:'快速建档'}).click();
 await dialog.getByRole('textbox',{name:'客户名称'}).fill('新建客户样稿');
 await dialog.getByRole('button',{name:'确认使用'}).click();
 await page.getByRole('button',{name:'新建客户样稿'}).waitFor();
 pass('快捷建档只需填写名称，草稿回填，不立即落库');
 await page.getByRole('button',{name:'从产品库添加'}).click();
 const picker=page.getByRole('dialog',{name:'选择产品添加'});
 await picker.waitFor();
 await shot('04-product-picker');
 await picker.getByRole('button',{name:'改为手工录入（仅管理员）'}).click();
 const manualConfirm=page.getByRole('alertdialog',{name:'切换为管理员手工录入？'});
 await manualConfirm.waitFor();
 await page.keyboard.press('Escape');
 assert(await picker.isVisible(),'Esc关闭上层确认后产品选择窗口必须继续打开');
 pass('管理员手工录入二次确认可取消，Esc不会误关闭底层选品弹窗');
 await picker.getByRole('button',{name:'关闭产品选择窗口'}).click();
 assert.match(await page.locator('text=产品明细（0）').first().textContent()||'',/0/);
 assert.equal(await page.locator('table[aria-label="单据明细录入"] tbody tr').count(),0);
 pass('选品弹窗取消不新增空白明细');
 await page.getByRole('button',{name:'从产品库添加'}).click();
 await picker.getByRole('button',{name:'选用产品 G0008-1'}).click();
 assert.equal(await page.locator('table[aria-label="单据明细录入"] tbody tr').count(),1);
 pass('选用产品后才写入单据明细，保留产品关联/规格');
 await page.getByRole('button',{name:'清空明细'}).click();
 const alert=page.getByRole('alertdialog',{name:'清空全部明细？'});
 await alert.waitFor();
 await shot('05-clear-lines-confirm');
 await alert.getByRole('button',{name:'取消'}).click();
 assert.equal(await page.locator('table[aria-label="单据明细录入"] tbody tr').count(),1);
 await page.getByRole('button',{name:'清空明细'}).click();
 await alert.getByRole('button',{name:'清空明细'}).click();
 assert.equal(await page.locator('table[aria-label="单据明细录入"] tbody tr').count(),0);
 pass('清空明细危险操作需要确认，取消保留，确认清空');
 await page.getByRole('button',{name:'返回',exact:true}).click();
 const leave=page.getByRole('alertdialog',{name:'放弃尚未保存的单据？'});
 await leave.waitFor();
 await leave.getByRole('button',{name:'取消'}).click();
 assert.equal(await page.getByRole('heading',{name:'新建单据'}).count(),1);
 pass('返回操作展示放弃修改确认，取消仍保留草稿');
 await page.setViewportSize({width:360,height:780});
 await shot('06-editor-mobile-360');
 const sizes=await page.evaluate(()=>({scroll:document.documentElement.scrollWidth,client:document.documentElement.clientWidth}));
 assert(sizes.scroll<=sizes.client+1,JSON.stringify(sizes));
 await page.getByRole('button',{name:'新建客户样稿'}).click();
 await dialog.waitFor();
 await shot('07-customer-mobile-dialog');
 const footerButtons=await dialog.locator('footer button').evaluateAll(nodes=>nodes.map(button=>{
  const b=button.getBoundingClientRect(),style=getComputedStyle(button);
  return {label:button.textContent?.trim(),width:b.width,scrollWidth:button.scrollWidth,whiteSpace:style.whiteSpace};
 }));
 assert(footerButtons.every(b=>b.width>=60&&b.scrollWidth<=b.width+2&&b.whiteSpace==='nowrap'),JSON.stringify(footerButtons));
 pass('360px客户弹窗底部两个操作按钮保持横排文字完整显示');
 assert(await dialog.isVisible());
 pass('360px窄屏页面无整体横向溢出，客户弹窗仍可操作');

 await page.keyboard.press('Escape');
 assert.equal(await dialog.count(),0,'客户弹窗应支持Esc关闭');
 assert(await page.getByRole('button',{name:'新建客户样稿'}).evaluate(node=>node===document.activeElement),'关闭弹窗焦点应回到客户入口');
 pass('客户弹窗Esc关闭并恢复触发按钮焦点');
 const type=page.getByLabel('单据类型');
 await type.selectOption({label:'销售发货码单'});
 assert.equal(await page.getByLabel('定金金额（元）').count(),1);
 await shot('08-sales-document-mobile');
 await type.selectOption({label:'定金单'});
 assert.equal(await page.getByLabel('定金比例（%）').count(),1);
 assert.equal(await page.getByLabel('已结清').count(),0);
 await shot('09-deposit-document-mobile');
 await type.selectOption({label:'样布码单'});
 assert.equal(await page.getByLabel('定金比例（%）').count(),0);
 pass('样布、销售、定金单切换仅显示对应财务控件');
 await page.getByText('单据签署与联系信息').click();
 assert.equal(await page.getByLabel('收货地址').count(),1);
 await shot('10-contact-detail-mobile');
 pass('联系签署信息默认收起，需要时展开录入');
 assert.deepEqual(errors,[]);
 await fs.writeFile(path.join(out,'qa-result.json'),JSON.stringify({checks,screens,errors,productionChanged:false},null,2));
 console.log('RESULT '+JSON.stringify({passed:checks.length,screens,errors}));
}catch(error){
 console.error('FAIL '+String(error?.stack||error));
 await fs.writeFile(path.join(out,'qa-failure.json'),JSON.stringify({checks,screens,errors,failure:String(error?.stack||error)},null,2));
 process.exitCode=1;
}finally{
 await browser?.close();
 await server?.close();
}
