import assert from 'node:assert/strict';
import {randomBytes} from 'node:crypto';
import ExcelJS from 'exceljs';
import {createFabricImportService} from '../../server/product-master/fabricExcelImport';
import {createFabric,getFabric} from '../../server/product-master/fabrics';
import {createPatternMaster} from '../../server/product-master/patternMasters';
import {createColorway} from '../../server/product-master/colorwayIdentity';
import {createV2Product} from '../../server/product-master/productsV2';
import {verifyFabricNumberSchema} from '../../server/product-master/fabricNumberSchema';
export async function rehearseFabricNumbers(pool:any):Promise<string[]>{
 const [db]:any=await pool.query('SELECT DATABASE() AS name');assert.match(db[0].name,/^fabric_release_check_[a-f0-9]{16}$/);
 await verifyFabricNumberSchema(pool);
 const name='FABNO'+randomBytes(6).toString('hex').toUpperCase();
 const [u]:any=await pool.query('INSERT INTO v2_access_users(username,username_normalized,display_name,password_hash,role) VALUES (?,?,?,?,?)',[name,name.toLowerCase(),name,'isolated-fixture-unusable','admin']);
 const [s]:any=await pool.query('INSERT INTO v2_access_sessions(user_id,token_hash,expires_at) VALUES (?,?,DATE_ADD(UTC_TIMESTAMP(),INTERVAL 1 HOUR))',[u.insertId,randomBytes(32).toString('hex')]);
 const actor:any={userId:String(u.insertId),sessionId:String(s.insertId),username:name,displayName:name,role:'admin',canManageProducts:true,canManageOwnOrders:true};
 const w=new ExcelJS.Workbook(),sheet=w.addWorksheet('Sheet1');
 sheet.addRow(['品号','品名','成分','克重','gsm/mm','门幅（里面CM）']);
 sheet.addRow([12101,'真丝双绉','100%桑蚕丝',12,'mm',137]);
 sheet.addRow([name+'-8','真丝欧根纱','100%桑蚕丝',8,'mm',137]);
 sheet.addRow(['底布 / '+name,'粘亚麻','55%人棉45%亚麻',165,'gsm',138]);
 const bytes=Buffer.from(await w.xlsx.writeBuffer()),service=createFabricImportService(pool,pool);
 let preview=await service.preview(actor,bytes,{filename:'底布编号 -OK.xlsx'});
 assert.equal(preview.rows.length,3);assert.equal(preview.counts.error,0);
 assert.equal(preview.rows[0].fabric?.fabricNo,'12101');
 const initialRows=preview.rows.filter(r=>r.existing&&r.fabric).map(r=>r.rowNumber);
 const result=await service.commit(actor,{token:preview.token,confirm:true,updateRows:initialRows});
 assert.equal(result.counts.failed,0);assert.equal(result.counts.created+result.counts.updated,3);
 preview=await service.preview(actor,bytes,{filename:'底布编号 -OK.xlsx'});
 assert.equal(preview.counts.skip,3);assert.equal(preview.counts.error,0);
 const duplicate=await service.commit(actor,{token:preview.token,confirm:true,updateRows:[]});assert.equal(duplicate.counts.skipped,3);assert.equal(duplicate.counts.failed,0);
 const [rows]:any=await pool.query('SELECT id,fabric_no,weight_unit,width_value FROM v2_fabrics WHERE fabric_no IN (?,?,?)',['12101',name+'-8','底布 / '+name]);
 assert.equal(rows.length,3);assert(rows.every((r:any)=>Number(r.width_value)>0));
 const m=await createPatternMaster(pool,actor,{masterNo:name}),c=await createColorway(pool,actor,m.id,{});
 const fabric=rows.find((r:any)=>r.fabric_no==='底布 / '+name);
 const product=await createV2Product(pool,actor,{patternColorwayId:c.id,fabricId:String(fabric.id)});
 assert.equal(product.productNo,name+'-1-底布 / '+name);
 assert.equal((await getFabric(pool,String(fabric.id)))?.fabricNo,'底布 / '+name);
 await assert.rejects(createFabric(pool,actor,{fabricNo:'  ',fabricName:'空编号'}),(e:any)=>e.status===400);
 await assert.rejects(pool.query("INSERT INTO v2_fabrics(fabric_no,fabric_name) VALUES ('','invalid')"));
 return ['registered nonempty-only fabric number constraint verified','real XLSX numeric/supplier text/unit/width preview and commit succeed','repeat import defaults to skip; explicit update remains required','nonempty free-form fabric usable in product creation and read','blank fabric rejected by domain and database; existing records retained'];
}
